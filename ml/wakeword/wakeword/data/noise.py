"""Synthetic room-noise backgrounds (own, generated): white/pink/brown noise, mains hum, fan.

Rows: licence "own", source "synthetic-noise", label "background", consent "n/a".
CLI: python -m wakeword.data.noise --config configs/base.yaml --out data/noise
"""
from __future__ import annotations

import argparse
import os

import numpy as np
import soundfile as sf
import yaml

from .manifest import Row, assign_splits, write_manifest

SR = 16000


def _coloured(n: int, power: float, rng: np.random.Generator) -> np.ndarray:
    spec = np.fft.rfft(rng.standard_normal(n))
    f = np.fft.rfftfreq(n, 1 / SR)
    f[0] = f[1]
    return np.fft.irfft(spec / f ** (power / 2), n)


def generate(kind: str, seconds: float, rng: np.random.Generator) -> np.ndarray:
    n = int(seconds * SR)
    t = np.arange(n) / SR
    if kind == "white":
        x = rng.standard_normal(n)
    elif kind == "pink":
        x = _coloured(n, 1.0, rng)
    elif kind == "brown":
        x = _coloured(n, 2.0, rng)
    elif kind == "hum":
        f0 = rng.choice([50.0, 60.0])
        x = sum(a * np.sin(2 * np.pi * f0 * h * t + rng.uniform(0, 6.28))
                for h, a in ((1, 1.0), (2, 0.5), (3, 0.3), (5, 0.15))) + 0.05 * rng.standard_normal(n)
    elif kind == "fan":
        f0 = rng.uniform(90, 160)
        mod = 1 + 0.1 * np.sin(2 * np.pi * rng.uniform(0.2, 1.0) * t)
        c = _coloured(n, 1.5, rng)
        x = 0.5 * c / np.std(c) + 0.4 * np.sin(2 * np.pi * f0 * t) * mod
    else:
        raise ValueError(f"unknown noise kind {kind!r}")
    x = x / (np.sqrt(np.mean(x ** 2)) + 1e-12) * 10 ** (-20 / 20)  # -20 dBFS RMS
    return np.clip(x, -1, 1).astype(np.float32)


def render_noise(cfg: dict, out_dir: str) -> list[Row]:
    nc = cfg["noise"]
    rng = np.random.default_rng(nc.get("seed", 0))
    ids = [f"{k}{i}" for k in nc["kinds"] for i in range(nc["clips_per_kind"])]
    splits = assign_splits(ids)
    os.makedirs(os.path.join(out_dir, "background"), exist_ok=True)
    rows = []
    for cid in ids:
        kind = cid.rstrip("0123456789")
        rel = f"background/noise_{cid}.wav"
        sf.write(os.path.join(out_dir, rel), generate(kind, nc["seconds"], rng), SR, subtype="PCM_16")
        rows.append(Row(path=rel, label="background", source="synthetic-noise", source_url="",
                        author="Swara (synthetic)", licence="own",
                        attribution=f"Synthetic {kind} noise generated by Swara",
                        speaker=f"synthetic-noise:{cid}", split=splits[cid], consent="n/a"))
    write_manifest(rows, os.path.join(out_dir, "manifest.csv"))
    return rows


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/base.yaml")
    ap.add_argument("--out", default="data/noise")
    args = ap.parse_args(argv)
    with open(args.config) as f:
        cfg = yaml.safe_load(f)
    print(f"wrote {len(render_noise(cfg, args.out))} clips to {args.out}")


if __name__ == "__main__":
    main()
