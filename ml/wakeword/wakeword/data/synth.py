"""Synthetic positives and near-misses rendered with Kokoro-82M (Apache-2.0), run locally.

Install on the training machine only (never shipped):
    pip install kokoro soundfile      # plus the system package espeak-ng
The `kokoro` import is lazy so tests and CI do not need it or the model download.
Every row is licence "own": generated by us, no person recorded, consent "n/a".

CLI: python -m wakeword.data.synth --config configs/base.yaml --out data/synth
"""
from __future__ import annotations

import argparse
import hashlib
from fractions import Fraction
import os
import re

import numpy as np
import soundfile as sf
import yaml
from scipy.signal import resample_poly

from .manifest import Row, write_manifest

KOKORO_SR = 24000
KOKORO_URL = "https://huggingface.co/hexgrad/Kokoro-82M"


def _kokoro_pipeline(lang_code: str):
    from kokoro import KPipeline  # lazy: pip install kokoro soundfile (+ espeak-ng)
    return KPipeline(lang_code=lang_code)


def _audio_of(chunk) -> np.ndarray:
    a = chunk[2] if isinstance(chunk, tuple) else chunk.audio
    if hasattr(a, "detach"):
        a = a.detach().cpu().numpy()
    return np.asarray(a, dtype=np.float32).reshape(-1)


def to_16k(audio: np.ndarray, src_sr: int, semitones: float = 0.0) -> np.ndarray:
    """Resample to 16 kHz; a non-zero `semitones` shifts pitch (and tempo) by resampling."""
    ratio = Fraction(16000 / (src_sr * 2.0 ** (semitones / 12.0))).limit_denominator(500)
    up, down = ratio.numerator, ratio.denominator
    return resample_poly(audio, up, down).astype(np.float32)


def _split_for(speaker: str) -> str:
    h = int(hashlib.sha1(speaker.encode()).hexdigest(), 16) % 10
    return "test" if h == 0 else "val" if h == 1 else "train"


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def render_all(cfg: dict, out_dir: str, pipeline_factory=_kokoro_pipeline) -> list[Row]:
    """Render every voice x text (x sampled speed/pitch variants); write WAVs + manifest.csv."""
    s = cfg["synth"]
    rng = np.random.default_rng(s.get("seed", 0))
    texts = [(t, "positive") for t in s["positives"]] + [(t, "near_miss") for t in s["near_misses"]]
    grid = [(sp, st) for sp in s["speeds"] for st in s["semitones"]]
    n_var = min(s["variants_per_voice_text"], len(grid))
    pipelines: dict[str, object] = {}
    rows: list[Row] = []
    os.makedirs(out_dir, exist_ok=True)
    for voice in s["voices"]:
        lang = voice[0]
        pipe = pipelines.get(lang) or pipelines.setdefault(lang, pipeline_factory(lang))
        for text, label in texts:
            for k, gi in enumerate(rng.choice(len(grid), size=n_var, replace=False)):
                speed, semis = grid[int(gi)]
                chunks = [_audio_of(c) for c in pipe(text, voice=voice, speed=speed)]
                if not chunks:
                    continue
                wav = to_16k(np.concatenate(chunks), KOKORO_SR, semis)
                peak = float(np.max(np.abs(wav))) or 1.0
                wav = wav / max(peak, 1.0)
                rel = f"{label}/{voice}_{_slug(text)}_{k}.wav"
                os.makedirs(os.path.join(out_dir, label), exist_ok=True)
                sf.write(os.path.join(out_dir, rel), wav, 16000, subtype="PCM_16")
                rows.append(Row(path=rel, label=label, source="kokoro-82m", source_url=KOKORO_URL,
                                author="Swara (synthetic, Kokoro-82M)", licence="own",
                                attribution="Synthetic speech generated with Kokoro-82M (Apache-2.0)",
                                speaker=voice, split=_split_for(voice), consent="n/a"))
    write_manifest(rows, os.path.join(out_dir, "manifest.csv"))
    return rows


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/base.yaml")
    ap.add_argument("--out", default="data/synth")
    args = ap.parse_args(argv)
    with open(args.config) as f:
        cfg = yaml.safe_load(f)
    rows = render_all(cfg, args.out)
    print(f"wrote {len(rows)} clips to {args.out}")


if __name__ == "__main__":
    main()
